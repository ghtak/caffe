-- JWT 액세스 토큰 갱신에 사용할 refresh token을 관리한다.
-- 토큰 원문은 저장하지 않고 해시로 조회한다.
-- 갱신 시 토큰을 교체하며, 같은 로그인에서 회전된 토큰은 family_id를 공유한다.
-- 사용된 토큰이 재사용되면 해당 계열의 활성 토큰을 취소한다.
-- 개별 토큰의 만료 시각은 갱신 시 연장할 수 있으나 계열의 절대 만료 시각을 넘지 않는다.
-- 계열의 절대 만료 시각은 회전해도 유지한다.
-- 재사용 탐지를 위해 사용된 토큰의 해시와 계열 정보를 계열 만료까지 보존한다.
-- 토큰 사용과 취소를 각각 기록하고 취소 사유를 보관한다.

CREATE TABLE IF NOT EXISTS conbira_auth_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES conbira_auth_users (id),
    family_id UUID NOT NULL,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    family_expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    revoke_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS conbira_auth_refresh_tokens_family_id_idx
    ON conbira_auth_refresh_tokens (family_id);

CREATE INDEX IF NOT EXISTS conbira_auth_refresh_tokens_user_id_idx
    ON conbira_auth_refresh_tokens (user_id);

COMMENT ON TABLE conbira_auth_refresh_tokens IS 'JWT 갱신 토큰과 회전 이력';
COMMENT ON COLUMN conbira_auth_refresh_tokens.id IS '갱신 토큰 ID';
COMMENT ON COLUMN conbira_auth_refresh_tokens.user_id IS '토큰이 발급된 사용자 ID';
COMMENT ON COLUMN conbira_auth_refresh_tokens.family_id IS '회전으로 이어진 갱신 토큰 계열 ID';
COMMENT ON COLUMN conbira_auth_refresh_tokens.token_hash IS '갱신 토큰의 해시';
COMMENT ON COLUMN conbira_auth_refresh_tokens.expires_at IS '개별 갱신 토큰의 만료 시각';
COMMENT ON COLUMN conbira_auth_refresh_tokens.family_expires_at IS '갱신 토큰 계열의 절대 만료 시각';
COMMENT ON COLUMN conbira_auth_refresh_tokens.used_at IS '토큰이 회전에 사용된 시각';
COMMENT ON COLUMN conbira_auth_refresh_tokens.revoked_at IS '토큰이 취소된 시각';
COMMENT ON COLUMN conbira_auth_refresh_tokens.revoke_reason IS '토큰 취소 사유';
COMMENT ON COLUMN conbira_auth_refresh_tokens.created_at IS '토큰 발급 시각';
