CREATE TABLE IF NOT EXISTS conbira_rbac_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS conbira_rbac_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS conbira_rbac_role_permissions (
    role_id BIGINT NOT NULL REFERENCES conbira_rbac_roles (id),
    permission_id BIGINT NOT NULL REFERENCES conbira_rbac_permissions (id),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS conbira_rbac_user_roles (
    user_id BIGINT NOT NULL REFERENCES conbira_auth_users (id),
    role_id BIGINT NOT NULL REFERENCES conbira_rbac_roles (id),
    PRIMARY KEY (user_id, role_id)
);

COMMENT ON TABLE conbira_rbac_roles IS '서비스 역할';
COMMENT ON COLUMN conbira_rbac_roles.id IS '역할 ID';
COMMENT ON COLUMN conbira_rbac_roles.code IS '역할 식별 코드';
COMMENT ON COLUMN conbira_rbac_roles.name IS '역할 표시 이름';
COMMENT ON COLUMN conbira_rbac_roles.description IS '역할 설명';

COMMENT ON TABLE conbira_rbac_permissions IS '서비스 권한';
COMMENT ON COLUMN conbira_rbac_permissions.id IS '권한 ID';
COMMENT ON COLUMN conbira_rbac_permissions.code IS '권한 식별 코드';
COMMENT ON COLUMN conbira_rbac_permissions.name IS '권한 표시 이름';
COMMENT ON COLUMN conbira_rbac_permissions.description IS '권한 설명';

COMMENT ON TABLE conbira_rbac_role_permissions IS '역할에 부여된 권한';
COMMENT ON COLUMN conbira_rbac_role_permissions.role_id IS '역할 ID';
COMMENT ON COLUMN conbira_rbac_role_permissions.permission_id IS '권한 ID';

COMMENT ON TABLE conbira_rbac_user_roles IS '사용자에게 부여된 역할';
COMMENT ON COLUMN conbira_rbac_user_roles.user_id IS '사용자 ID';
COMMENT ON COLUMN conbira_rbac_user_roles.role_id IS '역할 ID';

