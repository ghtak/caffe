CREATE TABLE IF NOT EXISTS conbira_auth_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'registered',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE conbira_auth_users IS '서비스 내부 사용자';
COMMENT ON COLUMN conbira_auth_users.id IS '내부 사용자 ID';
COMMENT ON COLUMN conbira_auth_users.nickname IS '서비스에서 표시하는 닉네임';
COMMENT ON COLUMN conbira_auth_users.status IS '상태값 (registered, active, inactive, withdrawn)';
COMMENT ON COLUMN conbira_auth_users.created_at IS '사용자 생성 시각';
COMMENT ON COLUMN conbira_auth_users.updated_at IS '사용자 정보의 마지막 변경 시각';


CREATE TABLE IF NOT EXISTS conbira_auth_user_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES conbira_auth_users (id),
    provider TEXT NOT NULL,
    provider_subject TEXT NOT NULL,
    email TEXT NOT NULL,
    password_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT conbira_auth_user_identities_provider_subject_unique
        UNIQUE (provider, provider_subject)
);

CREATE UNIQUE INDEX IF NOT EXISTS conbira_auth_user_identities_local_email_unique
    ON conbira_auth_user_identities (email)
    WHERE provider = 'local';

COMMENT ON TABLE conbira_auth_user_identities IS '사용자에게 연결된 로그인 식별 정보';
COMMENT ON COLUMN conbira_auth_user_identities.id IS '로그인 식별 정보 ID';
COMMENT ON COLUMN conbira_auth_user_identities.user_id IS '연결된 내부 사용자 ID';
COMMENT ON COLUMN conbira_auth_user_identities.provider IS '로그인 공급자 식별자: 직접 로그인은 local, Google 로그인은 google';
COMMENT ON COLUMN conbira_auth_user_identities.provider_subject IS '공급자 내 계정 식별자: local은 user_id의 문자열, OIDC는 sub';
COMMENT ON COLUMN conbira_auth_user_identities.email IS '정규화된 이메일. 직접 로그인에서는 로그인 식별자로 사용';
COMMENT ON COLUMN conbira_auth_user_identities.password_hash IS '직접 로그인에 사용하는 비밀번호 해시';
COMMENT ON COLUMN conbira_auth_user_identities.created_at IS '로그인 수단 연결 시각';
COMMENT ON COLUMN conbira_auth_user_identities.updated_at IS '로그인 식별 정보의 마지막 변경 시각';
