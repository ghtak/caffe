use std::sync::Arc;

use axum::body::{Body, to_bytes};
use axum::http::{Request, StatusCode, header};
use tower::ServiceExt as _;

async fn setup() -> anyhow::Result<(axum::Router, Arc<crate::app::Container>)> {
    let container = crate::test_support::container().await?;
    let router = crate::app::http::router(Arc::clone(&container))?;
    Ok((router, container))
}

#[tokio::test]
async fn permission_writes_require_manage_permission() -> anyhow::Result<()> {
    let (router, container) = setup().await?;
    let claims = serde_json::json!({"id": 42, "status": "active", "permissions": ["rbac.read"]});
    let token = container
        .jwt_token_service
        .issue("42", claims.as_object().unwrap().clone())?
        .token;
    for (method, path, body) in [
        (
            "POST",
            "/api/rbac/permissions",
            r#"{"code":"test","name":"Test","description":""}"#,
        ),
        ("DELETE", "/api/rbac/permissions/1", ""),
    ] {
        for (authorization, expected) in [
            (None, StatusCode::UNAUTHORIZED),
            (Some("Bearer invalid".to_owned()), StatusCode::UNAUTHORIZED),
            (Some(format!("Bearer {token}")), StatusCode::FORBIDDEN),
        ] {
            let mut request = Request::builder()
                .method(method)
                .uri(path)
                .header(header::CONTENT_TYPE, "application/json");
            if let Some(authorization) = authorization {
                request = request.header(header::AUTHORIZATION, authorization);
            }
            let response = router
                .clone()
                .oneshot(request.body(Body::from(body))?)
                .await?;
            // 인증이 없거나 관리 권한이 없으면 쓰기를 거부한다.
            assert_eq!(response.status(), expected);
        }
    }
    Ok(())
}

#[tokio::test]
async fn creates_and_deletes_permissions_but_rejects_assigned_permission() -> anyhow::Result<()> {
    let (router, container) = setup().await?;
    {
        let mut connection = container.db.conn().await?;
        sqlx::query("CREATE TEMPORARY TABLE conbira_rbac_permissions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE, name TEXT NOT NULL, description TEXT NOT NULL)")
            .execute(connection.handle().conn()).await?;
        sqlx::query("CREATE TEMPORARY TABLE conbira_rbac_role_permissions (role_id BIGINT NOT NULL, permission_id BIGINT NOT NULL REFERENCES conbira_rbac_permissions(id))")
            .execute(connection.handle().conn()).await?;
    }
    let claims = serde_json::json!({"id": 42, "status": "active", "permissions": ["rbac.permission.manage"]});
    let token = container
        .jwt_token_service
        .issue("42", claims.as_object().unwrap().clone())?
        .token;
    let create = Request::builder()
        .method("POST")
        .uri("/api/rbac/permissions")
        .header(header::AUTHORIZATION, format!("Bearer {token}"))
        .header(header::CONTENT_TYPE, "application/json")
        .body(Body::from(
            r#"{"code":"test.manage","name":"Test","description":"Test permission"}"#,
        ))?;
    let response = router.clone().oneshot(create).await?;
    // 생성된 권한을 ID와 함께 반환한다.
    assert_eq!(response.status(), StatusCode::OK);
    let body: serde_json::Value =
        serde_json::from_slice(&to_bytes(response.into_body(), 4096).await?)?;
    let id = body["data"]["id"].as_i64().unwrap();
    assert_eq!(
        body,
        serde_json::json!({"code": "OK", "data": {"id": id, "code": "test.manage", "name": "Test", "description": "Test permission"}})
    );
    let duplicate = Request::builder()
        .method("POST")
        .uri("/api/rbac/permissions")
        .header(header::AUTHORIZATION, format!("Bearer {token}"))
        .header(header::CONTENT_TYPE, "application/json")
        .body(Body::from(
            r#"{"code":"test.manage","name":"Duplicate","description":""}"#,
        ))?;
    let response = router.clone().oneshot(duplicate).await?;
    // 중복 코드는 클라이언트 오류로 반환하고 기존 권한을 유지한다.
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    let body: serde_json::Value =
        serde_json::from_slice(&to_bytes(response.into_body(), 4096).await?)?;
    assert_eq!(
        body,
        serde_json::json!({"code": "INVALID_REQUEST", "message": "Permission code already exists"})
    );
    {
        let mut connection = container.db.conn().await?;
        let name: String =
            sqlx::query_scalar("SELECT name FROM conbira_rbac_permissions WHERE id = $1")
                .bind(id)
                .fetch_one(connection.handle().conn())
                .await?;
        assert_eq!(name, "Test");
        sqlx::query("INSERT INTO conbira_rbac_role_permissions VALUES (1, $1)")
            .bind(id)
            .execute(connection.handle().conn())
            .await?;
    }
    let delete = || {
        Request::builder()
            .method("DELETE")
            .uri(format!("/api/rbac/permissions/{id}"))
            .header(header::AUTHORIZATION, format!("Bearer {token}"))
            .body(Body::empty())
            .unwrap()
    };
    let response = router.clone().oneshot(delete()).await?;
    // 역할에 연결된 권한은 삭제되지 않는다.
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    {
        let mut connection = container.db.conn().await?;
        let exists: bool = sqlx::query_scalar(
            "SELECT EXISTS(SELECT 1 FROM conbira_rbac_permissions WHERE id = $1)",
        )
        .bind(id)
        .fetch_one(connection.handle().conn())
        .await?;
        assert!(exists);
        sqlx::query("DELETE FROM conbira_rbac_role_permissions WHERE permission_id = $1")
            .bind(id)
            .execute(connection.handle().conn())
            .await?;
    }
    let response = router.clone().oneshot(delete()).await?;
    // 연결을 해제하면 삭제되며 반복 삭제는 대상을 찾지 못한다.
    assert_eq!(response.status(), StatusCode::OK);
    let body: serde_json::Value =
        serde_json::from_slice(&to_bytes(response.into_body(), 4096).await?)?;
    assert_eq!(body, serde_json::json!({"code": "OK"}));
    assert_eq!(
        router.oneshot(delete()).await?.status(),
        StatusCode::NOT_FOUND
    );
    Ok(())
}
